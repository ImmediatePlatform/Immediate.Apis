using System.Diagnostics.CodeAnalysis;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Immediate.Apis;

internal sealed record FileSystemRoutingSettings(bool Enabled, string ProjectDirectory, string RootDirectory, int NamingPolicy)
{
	public static FileSystemRoutingSettings Create(Compilation compilation, AnalyzerConfigOptions options)
	{
		var attribute = compilation.Assembly.GetAttributes().FirstOrDefault(a => string.Equals(a.AttributeClass?.ToDisplayString(), "Immediate.Apis.Shared.FileSystemRoutingAttribute", StringComparison.Ordinal));
		_ = options.TryGetValue("build_property.ProjectDir", out var projectDirectory);
		return new(attribute is not null, projectDirectory ?? "",
			attribute?.NamedArguments.FirstOrDefault(a => string.Equals(a.Key, "RootDirectory", StringComparison.Ordinal)).Value.Value as string ?? "",
			attribute?.NamedArguments.FirstOrDefault(a => string.Equals(a.Key, "NamingPolicy", StringComparison.Ordinal)).Value.Value is int policy ? policy : 2);
	}

	public string? Error =>
		NamingPolicy is < 0 or > 4 ? "The route naming policy is invalid."
		: !FileSystemRouting.IsAbsolute(ProjectDirectory) ? "ProjectDir must be available as an absolute compiler-visible MSBuild property."
		: FileSystemRouting.IsAbsolute(RootDirectory) || RootDirectory.Replace('\\', '/').Split('/').Contains("..", StringComparer.Ordinal)
			? "RootDirectory must be a project-relative directory without '..' segments."
		: null;
}

internal sealed record FileSystemGroup(string ClassName, string? ParentClassName, string FilePath, string Route);
internal sealed record DirectoryRouteGroup(string Directory, string ClassName, string? ParentClassName, string Route, bool IsDeclared);
internal sealed record FileSystemRoute(string? GroupClassName, string? Error);

/// <summary>Shared by the generator and analyzers; uses compiler paths only, never filesystem IO.</summary>
internal sealed class FileSystemRouting(FileSystemRoutingSettings settings, IReadOnlyList<FileSystemGroup> declarations)
{
	private readonly Dictionary<string, DirectoryRouteGroup> _groups = [with(GetPathComparer(settings.ProjectDirectory))];
	private readonly Dictionary<string, string> _segments = [with(GetPathComparer(settings.ProjectDirectory))];
	public IEnumerable<DirectoryRouteGroup> Groups => _groups.Values.OrderBy(g => g.Directory, StringComparer.Ordinal);

	public static IEnumerable<string> GetPartialFiles(INamedTypeSymbol symbol, CancellationToken token) =>
		symbol.DeclaringSyntaxReferences
			.Where(r => r.SyntaxTree.GetRoot(token).GetLeadingTrivia().ToFullString().IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) < 0)
			.Select(r => r.SyntaxTree.FilePath);

	public FileSystemRoute Resolve(string filePath, IEnumerable<string> partialFiles)
	{
		if (settings.Error is { } error)
			return new(GroupClassName: null, Error: error);
		if (GetDirectory(filePath) is not { } directory)
			return new(GroupClassName: null, Error: "The mapping attribute must be in a source file inside RootDirectory. Linked files outside that directory are not supported.");
		if (partialFiles.Any(p => !GetPathComparer(settings.ProjectDirectory).Equals(GetDirectory(p), directory)))
			return new(GroupClassName: null, Error: "All declarations of a file-routed partial handler must be in the same directory.");

		string? parent = null;
		var current = "";
		foreach (var segment in Enumerable.Repeat("", 1).Concat(directory.Split('/').Where(s => s.Length > 0)))
		{
			var parentDirectory = current;
			current = current.Length == 0 ? segment : current + "/" + segment;
			var matches = declarations.Where(g => g.ParentClassName is null && GetPathComparer(settings.ProjectDirectory).Equals(GetDirectory(g.FilePath), current)).ToArray();
			if (matches.Length > 1)
				return new(GroupClassName: null, Error: $"Directory '{current}' contains multiple top-level route groups. Select a group explicitly with MapGroup<T>.");
			var route = matches.Length == 1 ? matches[0].Route : ConvertSegment(segment, settings.NamingPolicy);
			if (matches.Length == 0 && segment.Length > 0 && route.Length == 0)
				return new(GroupClassName: null, Error: $"Directory '{current}' has no usable route segment after applying the naming policy.");
			if (segment.Length > 0)
			{
				var key = parentDirectory + "\0" + route.ToUpperInvariant();
				if (_segments.TryGetValue(key, out var previous) && !GetPathComparer(settings.ProjectDirectory).Equals(previous, current))
					return new(GroupClassName: null, Error: $"Directories '{previous}' and '{current}' resolve to the same route segment '{route}'.");
				_segments[key] = current;
			}
			// The root needs a node only when it contains a declared group.
			if (current.Length == 0 && matches.Length == 0)
				continue;
			if (_groups.TryGetValue(current, out var existing))
			{
				parent = existing.ClassName;
				continue;
			}

			var className = matches.Length == 1 ? matches[0].ClassName : GetClassName(current);
			_groups[current] = new(current, className, parent, route, matches.Length == 1);
			parent = className;
		}

		return new(parent, Error: null);
	}

	public string? GetDirectory(string filePath)
	{
		if (!IsAbsolute(filePath) || settings.Error is not null)
			return null;
		var root = Normalize(settings.ProjectDirectory + "/" + settings.RootDirectory).TrimEnd('/') + "/";
		var file = Normalize(filePath);
		var comparison = (root.Length > 1 && root[1] == ':') || root.StartsWith("//", StringComparison.Ordinal)
			? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
		if (!file.StartsWith(root, comparison))
			return null;
		var relative = file[root.Length..];
		var slash = relative.LastIndexOf('/');
		return slash < 0 ? "" : relative[..slash];
	}

	public string GetGroupPrefix(string? className)
	{
		if (className is null)
			return "";
		var directoryGroup = _groups.Values.FirstOrDefault(g => string.Equals(g.ClassName, className, StringComparison.Ordinal));
		if (directoryGroup is not null)
			return Join(GetGroupPrefix(directoryGroup.ParentClassName), directoryGroup.Route);
		var declaration = declarations.FirstOrDefault(g => string.Equals(g.ClassName, className, StringComparison.Ordinal));
		return declaration is null ? "" : Join(GetGroupPrefix(declaration.ParentClassName), declaration.Route);
	}

	public static string Join(string prefix, string route) => (prefix.TrimEnd('/') + "/" + route.Trim('/')).TrimEnd('/');

	public static bool IsAbsolute(string path) => (path.Length > 0 && path[0] == '/')
		|| path.StartsWith("\\\\", StringComparison.Ordinal) || (path.Length > 2 && char.IsLetter(path[0]) && path[1] == ':' && path[2] is '/' or '\\');

	private static string Normalize(string path)
	{
		var parts = new List<string>();
		foreach (var part in path.Replace('\\', '/').Split('/').Where(p => p.Length > 0))
		{
			if (string.Equals(part, ".", StringComparison.Ordinal)) continue;
			if (string.Equals(part, "..", StringComparison.Ordinal) && parts.Count > 0) parts.RemoveAt(parts.Count - 1);
			else if (!string.Equals(part, "..", StringComparison.Ordinal)) parts.Add(part);
		}

		return (IsUncPath(path) ? "//" : path.Length > 0 && path[0] == '/' ? "/" : "") + string.Join("/", parts);
	}

	private static bool IsUncPath(string path) => path.StartsWith("//", StringComparison.Ordinal) || path.StartsWith("\\\\", StringComparison.Ordinal);

	private static StringComparer GetPathComparer(string path) =>
		path.Length > 1 && path[1] == ':' || IsUncPath(path)
			? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal;

	private static string GetClassName(string directory)
	{
		// Encode every UTF-16 code unit: deterministic, collision-free, and valid as a C# identifier.
		var name = new StringBuilder("global::Immediate.Apis.Generated.FileSystemDirectory_");
		foreach (var c in directory)
			name.Append(((int)c).ToString("x4", System.Globalization.CultureInfo.InvariantCulture));
		return name.ToString();
	}

	[SuppressMessage("Globalization", "CA1308:Normalize strings to uppercase", Justification = "The public route naming policies intentionally produce lowercase paths.")]
	private static string ConvertSegment(string segment, int policy)
	{
		var words = new List<string>();
		var word = new StringBuilder();
		for (var i = 0; i < segment.Length; i++)
		{
			var c = segment[i];
			if (!char.IsLetterOrDigit(c))
			{
				if (word.Length > 0) { words.Add(word.ToString()); word.Clear(); }

				continue;
			}

			if (word.Length > 0 && char.IsUpper(c) && (char.IsLower(segment[i - 1]) || char.IsDigit(segment[i - 1])
				|| (i + 1 < segment.Length && char.IsLower(segment[i + 1]) && char.IsUpper(segment[i - 1]))))
			{
				words.Add(word.ToString()); word.Clear();
			}

			word.Append(c);
		}

		if (word.Length > 0) words.Add(word.ToString());
		return string.Join(policy == 3 ? "-" : policy == 4 ? "_" : "", words.Select((w, i) =>
			policy == 0 || (policy == 1 && i > 0) ? char.ToUpperInvariant(w[0]) + w[1..].ToLowerInvariant() : w.ToLowerInvariant()));
	}
}
